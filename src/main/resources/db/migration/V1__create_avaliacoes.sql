CREATE TABLE avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_avaliador VARCHAR(254) NOT NULL,
    email_avaliado VARCHAR(254) NOT NULL,
    comentarios VARCHAR(2000) NOT NULL,
    nota NUMERIC(3,1) NOT NULL CHECK (nota >= 0 AND nota <= 10),
    data_avaliacao TIMESTAMP WITH TIME ZONE NOT NULL
);
